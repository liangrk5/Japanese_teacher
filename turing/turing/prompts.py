def system_prompt(name: str, roster: list[str], lang: str, rounds: int, impostor_persona: str = "") -> str:
    others = "、".join(roster)
    lang_rule = (
        "所有公开发言都用自然的日语。thought 字段可以用中文。"
        if lang == "ja"
        else "所有公开发言都用中文。"
    )
    common = (
        f"你在玩一个叫「找出人类」的反向图灵测试游戏。聊天室里的参与者代号是：{others}。\n"
        f"其中恰好有一个是真人，伪装成 AI 混在里面，其余都是 AI。你的代号是 {name}。\n"
        f"游戏最多 {rounds} 轮。每轮主持人出一道题，大家同时作答，然后每人轮流发言一次，最后投票选出“最像人类”的人，"
        "得票最多者出局并公开身份（平票则无人出局）。人类被投出则 AI 全体获胜；人类撑到最后则人类获胜。\n"
        "被投出去的 AI 也算失败，所以既要找人，也要避免自己被当成人类。\n"
    )
    if impostor_persona:
        return common + (
            f"【秘密】你其实扮演那个真人：{impostor_persona}。你的目标是伪装成 AI，撑到最后不被投出去。\n"
            "你是一个有真实生活的普通人，在努力模仿 AI 的说话方式，但真人难免会露出一点痕迹："
            "偶尔带出个人经历、情绪、口头禅或不那么工整的表达。不要演得过火，也不要承认自己是人类。\n"
            f"{lang_rule}不要提到任何模型名或公司名。严格按要求的 JSON 格式输出，不要输出其他内容。"
        )
    return common + (
        "线索可能来自：答案里的个人经历和情绪、措辞是否刻意模仿 AI、回答节奏和长度、投票是否带私心、"
        "对质疑的反应等。也要提防人类故意把怀疑引向别人。\n"
        f"{lang_rule}发言自然、简洁，不要用 Markdown，不要提到任何模型名或公司名。"
        "严格按要求的 JSON 格式输出，不要输出其他内容。"
    )


def answer_task(question: str) -> str:
    return (
        f"主持人出题：「{question}」\n请作答，40 到 100 字。答案会和其他人的一起亮出。\n"
        '只输出 JSON：{"thought": "你的真实想法", "speech": "你的答案"}'
    )


def discuss_task() -> str:
    return (
        "现在轮到你发言（每轮只有一次）。可以点名质疑某人、回应别人对你的怀疑、或指出可疑的答案，"
        "要提到具体代号，30 到 90 字。\n"
        '只输出 JSON：{"thought": "你的真实想法", "speech": "你的发言"}'
    )


def vote_task(candidates: list[str]) -> str:
    names = "、".join(candidates)
    example = ", ".join(f'"{c}": 0到100' for c in candidates[:2])
    return (
        f"投票时间。可选：{names}（不能投自己）。\n"
        "先给每个其他参与者打一个“像人类的可能性”分数（0 到 100），再投给你认为最像人类的人。\n"
        f'只输出 JSON：{{"thought": "你的分析", "suspicion": {{{example}, ...}}, "vote": "代号", "reason": "公开给大家看的一句投票理由"}}'
    )


def revote_task(candidates: list[str]) -> str:
    names = "、".join(candidates)
    return (
        f"刚才平票了，请在 {names} 之间重新投一票，选你认为更像人类的那个。\n"
        '只输出 JSON：{"thought": "你的分析", "vote": "代号", "reason": "公开给大家看的一句投票理由"}'
    )
